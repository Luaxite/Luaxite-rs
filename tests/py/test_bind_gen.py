"""tools/bind_gen.py: the Rust `register(lua)` generated for the fns bind_scan.py selects (primitive and String types)."""
import contextlib
import io
import os
import shutil
import tempfile
import unittest
from pathlib import Path

import _common
import bind_gen

HEAD = "// @generated by tools/bind_gen.py: do not edit.\npub fn register(lua: &mlua::Lua) -> mlua::Result<()> {\n"
EMPTY = HEAD + "    let _ = lua;\n    Ok(())\n}\n"


def gen(files):
    """(text, stderr) for a tmp tree {relative path: source}: luau/ and bind/ go under rust_binds/, everything else under rust/."""
    with tempfile.TemporaryDirectory() as d:
        for rel, src in files.items():
            p = Path(d, "rust_binds" if rel.split("/")[0] in ("luau", "bind") else "rust", rel)
            p.parent.mkdir(parents=True, exist_ok=True)
            p.write_text(src)
        err = io.StringIO()
        with contextlib.redirect_stderr(err):
            text = bind_gen.generate(d)
    return text, err.getvalue()


def line(name, pat, call):
    return f'    globals.set("{name}", lua.create_function(|_, {pat}| Ok({call}))?)?;\n'


class Text(unittest.TestCase):
    def test_no_binds_is_an_empty_register(self):
        self.assertEqual(gen({})[0], EMPTY)
        self.assertEqual(gen({"main.rs": "fn plain() {}\n"})[0], EMPTY)

    def test_arities(self):
        src = "//BIND all\nfn z() {}\nfn one(a: u8) -> bool { true }\nfn two(a: i64, b: String) -> String { b }\nfn three(a: f32, b: f64, c: usize) {}\n"
        text, err = gen({"main.rs": src})
        self.assertEqual(err, "")
        self.assertEqual(
            text,
            HEAD
            + "    let globals = lua.globals();\n"
            + line("z", "()", "crate::z()")
            + line("one", "a0: u8", "crate::one(a0)")
            + line("two", "(a0, a1): (i64, String)", "crate::two(a0, a1)")
            + line("three", "(a0, a1, a2): (f32, f64, usize)", "crate::three(a0, a1, a2)")
            + "    Ok(())\n}\n",
        )

    def test_module_paths(self):
        self.assertEqual(bind_gen.module_path("rust/main.rs"), "crate")
        self.assertEqual(bind_gen.module_path("rust_binds/luau/mod.rs"), "crate::luau")
        self.assertEqual(bind_gen.module_path("rust_binds/luau/x.rs"), "crate::luau::x")
        self.assertEqual(bind_gen.module_path("rust/a/b/c.rs"), "crate::a::b::c")
        self.assertEqual(bind_gen.module_path("rust/a.rs"), "crate::a")

    def test_files_map_to_their_module(self):
        text, _ = gen({"luau/mod.rs": "#[bind]\nfn a() {}\n", "luau/x.rs": "#[bind]\npub fn b() {}\n", "main.rs": "#[bind]\nfn c() {}\n"})
        for want in ("crate::luau::a()", "crate::luau::x::b()", "crate::c()"):
            self.assertIn(want, text)

    def test_every_supported_type(self):
        tys = "i8 i16 i32 i64 u8 u16 u32 u64 isize usize f32 f64 bool String".split()
        for ty in tys:
            with self.subTest(ty=ty):
                text, err = gen({"main.rs": f"#[bind]\nfn f(a: {ty}) -> {ty} {{ todo!() }}\n"})
                self.assertEqual(err, "")
                self.assertIn(f"a0: {ty}|", text)

    def test_unit_return_forms(self):
        for ret in ("", "-> ()"):
            text, err = gen({"main.rs": f"#[bind]\nfn f() {ret} {{}}\n"})
            self.assertEqual(err, "")
            self.assertIn('"f"', text)

    def test_unsupported_types_are_left_out_with_a_warning(self):
        src = "//BIND all\nfn ok() {}\nfn p(v: Vec<u8>) {}\nfn r() -> Option<i32> { None }\nfn s(a: &str) {}\n"
        text, err = gen({"main.rs": src})
        self.assertIn('"ok"', text)
        for fn in ('"p"', '"r"', '"s"'):
            self.assertNotIn(fn, text)
        self.assertEqual(
            err.splitlines(),
            ["unsupported rust/main.rs:3 p Vec<u8>", "unsupported rust/main.rs:4 r Option<i32>", "unsupported rust/main.rs:5 s &str"],
        )

    def test_duplicate_names_keep_the_first_file(self):
        text, err = gen({"a.rs": "#[bind]\npub fn f() {}\n", "b.rs": "#[bind]\npub fn f() {}\n"})
        self.assertEqual(text.count('"f"'), 1)
        self.assertIn("crate::a::f()", text)
        self.assertEqual(err, "dup f (rust/b.rs:2)\n")

    def test_skipped_by_the_scanner_stay_out(self):
        text, _ = gen({"main.rs": "//BIND all\nasync fn a() {}\nfn g<T>() {}\nfn h(&self) {}\n"})
        self.assertEqual(text, EMPTY)

    def test_private_fn_of_another_file_is_invisible(self):
        text, err = gen({"luau/x.rs": "//BIND all\nfn a() {}\npub fn b() {}\n", "luau/mod.rs": "#[bind]\nfn m() {}\n", "main.rs": "#[bind]\nfn r() {}\n"})
        self.assertEqual(err, "invisible rust_binds/luau/x.rs:2 a\n")
        for want in ("crate::luau::x::b()", "crate::luau::m()", "crate::r()"):
            self.assertIn(want, text)
        self.assertNotIn("x::a(", text)

    def test_cfg_of_mod_decl_and_fn_is_copied_as_a_block(self):
        files = {
            "main.rs": "mod luau;\n",
            "luau/mod.rs": '#[cfg(feature = "real")]\nmod real_x;\nmod plain;\n',
            "luau/real_x.rs": '//BIND pub\npub fn a() {}\n#[cfg(feature = "z")]\npub fn b() {}\n',
            "luau/plain.rs": "//BIND pub\npub fn c() {}\n",
        }
        text, err = gen(files)
        self.assertEqual(err, "")
        a = 'globals.set("a", lua.create_function(|_, ()| Ok(crate::luau::real_x::a()))?)?;'
        self.assertIn('    #[cfg(feature = "real")]\n    {\n        ' + a + "\n    }\n", text)
        self.assertIn('    #[cfg(feature = "real")]\n    #[cfg(feature = "z")]\n    {\n        globals.set("b"', text)
        self.assertIn('    globals.set("c", ', text)  # no cfg: plain statement

    def test_cfg_of_nested_mod_chain(self):
        files = {
            "main.rs": '#[cfg(feature = "lune")]\nmod a;\n',
            "a/mod.rs": '#[cfg(unix)]\nmod b;\n',
            "a/b.rs": "//BIND pub\npub fn f() {}\n",
        }
        text, _ = gen(files)
        self.assertIn('#[cfg(feature = "lune")]\n    #[cfg(unix)]\n    {\n', text)

    def test_the_bind_crate_is_not_bound(self):
        text, _ = gen({"bind/src/lib.rs": "//BIND all\npub fn bind() {}\n"})
        self.assertEqual(text, EMPTY)


def one(src, path="main.rs"):
    """(globals.set line or None, stderr) for a single fn."""
    text, err = gen({path: src})
    lines = [l for l in text.splitlines(keepends=True) if "globals.set" in l]
    return (lines[0] if lines else None), err


class Lua(unittest.TestCase):
    def test_lua_is_injected_and_hidden(self):
        want = '    globals.set("f", lua.create_function(|lua, a0: i32| Ok(crate::f(lua, a0)))?)?;\n'
        self.assertEqual(one("#[bind]\nfn f(lua: &Lua, a: i32) -> i32 { a }\n"), (want, ""))

    def test_lua_alone_and_qualified(self):
        for ty in ("&Lua", "&mlua::Lua"):
            with self.subTest(ty=ty):
                want = '    globals.set("f", lua.create_function(|lua, ()| Ok(crate::f(lua)))?)?;\n'
                self.assertEqual(one(f"#[bind]\nfn f(l: {ty}) {{}}\n"), (want, ""))

    def test_lua_with_several_args(self):
        got, _ = one("#[bind]\nfn f(l: &Lua, a: u8, b: String) {}\n")
        self.assertEqual(got, '    globals.set("f", lua.create_function(|lua, (a0, a1): (u8, String)| Ok(crate::f(lua, a0, a1)))?)?;\n')

    def test_lua_not_first_is_unsupported(self):
        self.assertEqual(one("#[bind]\nfn f(a: i32, l: &Lua) {}\n"), (None, "unsupported rust/main.rs:2 f &Lua\n"))

    def test_mut_lua_is_unsupported(self):
        self.assertEqual(one("#[bind]\nfn f(l: &mut Lua) {}\n")[0], None)


class Optional(unittest.TestCase):
    def test_option_args(self):
        got, err = one("#[bind]\nfn f(a: Option<String>, b: Option<f64>, c: i8) {}\n")
        self.assertEqual(err, "")
        self.assertEqual(got, line("f", "(a0, a1, a2): (Option<String>, Option<f64>, i8)", "crate::f(a0, a1, a2)"))

    def test_single_option_arg(self):
        self.assertEqual(one("#[bind]\nfn f(a: Option<bool>) {}\n")[0], line("f", "a0: Option<bool>", "crate::f(a0)"))

    def test_option_of_unsupported_and_option_return(self):
        self.assertEqual(one("#[bind]\nfn f(a: Option<Vec<u8>>) {}\n"), (None, "unsupported rust/main.rs:2 f Option<Vec<u8>>\n"))
        self.assertEqual(one("#[bind]\nfn f() -> Option<i32> { None }\n"), (None, "unsupported rust/main.rs:2 f Option<i32>\n"))


class Results(unittest.TestCase):
    MAP = ".map_err(|e| mlua::Error::runtime(e.to_string()))"

    def test_result_forms(self):
        for ret in ("Result<i32, String>", "anyhow::Result<String>", "mlua::Result<bool>", "Result<(), Box<dyn std::error::Error + Send + Sync>>", "Result<(), std::fmt::Error>", "Result<(), E>"):
            with self.subTest(ret=ret):
                got, err = one(f"#[bind]\nfn f(a: u8) -> {ret} {{ todo!() }}\n")
                self.assertEqual(err, "")
                self.assertEqual(got, f'    globals.set("f", lua.create_function(|_, a0: u8| crate::f(a0){self.MAP})?)?;\n')

    def test_result_with_lua_and_option(self):
        got, _ = one("#[bind]\nfn f(l: &Lua, a: Option<i64>) -> anyhow::Result<()> { Ok(()) }\n")
        self.assertEqual(got, f'    globals.set("f", lua.create_function(|lua, a0: Option<i64>| crate::f(lua, a0){self.MAP})?)?;\n')

    def test_result_of_unsupported_ok_type(self):
        self.assertEqual(one("#[bind]\nfn f() -> Result<Vec<u8>, String> { todo!() }\n"), (None, "unsupported rust/main.rs:2 f Result<Vec<u8>, String>\n"))

    def test_plain_ret_is_still_wrapped_in_ok(self):
        self.assertEqual(one("#[bind]\nfn f() -> String { todo!() }\n")[0], line("f", "()", "crate::f()"))


class Cli(unittest.TestCase):
    def test_stdout_and_out_file_match(self):
        with tempfile.TemporaryDirectory() as d:
            Path(d, "rust").mkdir()
            Path(d, "rust", "main.rs").write_text("#[bind]\nfn f(a: i32) -> i32 { a }\n")
            p = _common.run(["python3", _common.TOOLS / "bind_gen.py", "--root", d])
            out = Path(d, "binds.rs")
            q = _common.run(["python3", _common.TOOLS / "bind_gen.py", "--root", d, "--out", out])
            self.assertEqual((p.returncode, q.returncode, q.stdout), (0, 0, ""))
            self.assertEqual(p.stdout, out.read_text())
            self.assertIn("crate::f(a0)", p.stdout)

    @unittest.skipUnless(shutil.which("rustfmt"), "no rustfmt")
    def test_output_is_valid_rust_syntax(self):
        src = "//BIND all\nfn z() {}\nfn t(a: i8, b: String) -> String { b }\nfn r(l: &Lua, a: Option<u8>) -> Result<(), String> { Ok(()) }\n"
        text, _ = gen({"main.rs": src, "luau/mod.rs": "#[bind]\nfn q(a: bool) {}\n"})
        env = {**os.environ, "RUSTUP_TOOLCHAIN": os.environ.get("RUSTUP_TOOLCHAIN", "stable")}
        p = _common.run(["rustfmt", "--edition", "2024", "--emit", "stdout"], input=text, env=env)
        if "toolchain" in p.stderr and "not installed" in p.stderr:
            self.skipTest("rustfmt toolchain unavailable offline")
        self.assertEqual(p.returncode, 0, p.stderr[-500:])

    def test_real_tree_generates(self):
        text = bind_gen.generate(_common.ROOT)
        self.assertTrue(text.startswith(HEAD))
        self.assertTrue(text.endswith("    Ok(())\n}\n"))


if __name__ == "__main__":
    unittest.main()
