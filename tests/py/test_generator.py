"""tools/luaxite_gen.py end to end on the fixture: outputs, determinism, golden, structure, error handling."""
import hashlib
import re
import tempfile
import unittest
from pathlib import Path

from _common import FAKE, FAKE_RDJ, ROOT, TOOLS, d_luau_functions, generate, read, run
import sys

EVENTS = ["init", "login", "chat", "tick", "add_player", "keep_alive", "disconnect", "connection_failed", "death"]


def sha(p):
    return hashlib.sha1(Path(p).read_bytes()).hexdigest()


class Base(unittest.TestCase):
    @classmethod
    def setUpClass(cls):
        cls.rust, cls.luau, cls.proc = generate()
        cls.dl = (cls.luau / "azalea.d.luau").read_text()
        cls.client = (cls.rust / "gen_client.rs").read_text()
        cls.events = (cls.rust / "gen_events.rs").read_text()
        cls.types = (cls.rust / "gen_types.rs").read_text()
        cls.report = (cls.luau / "GEN_REPORT.md").read_text()


class Outputs(Base):

    def test_exit_status_is_zero(self):
        self.assertEqual(self.proc.returncode, 0, self.proc.stderr)

    def test_all_five_files_are_written(self):
        for f in ["gen_client.rs", "gen_events.rs", "gen_types.rs"]:
            self.assertTrue((self.rust / f).stat().st_size > 500, f)
        for f in ["azalea.d.luau", "GEN_REPORT.md"]:
            self.assertTrue((self.luau / f).stat().st_size > 500, f)

    def test_generated_marker_in_every_file(self):
        for t in (self.client, self.events, self.types, self.dl):
            self.assertIn("@generated by tools/luaxite_gen.py", t.splitlines()[0])

    def test_matches_the_committed_harness_output(self):
        for name, d in [("gen_client.rs", self.rust), ("gen_events.rs", self.rust), ("gen_types.rs", self.rust)]:
            self.assertEqual(sha(d / name), sha(ROOT / "harness/src/luau" / name), name)
        for name in ["azalea.d.luau", "GEN_REPORT.md"]:
            self.assertEqual(sha(self.luau / name), sha(ROOT / "harness/luau" / name), name)

    def test_matches_golden_sha1_list(self):
        gold = {}
        for line in (ROOT / "tools/golden/fake.sha1").read_text().splitlines():
            if line and not line.startswith("#"):
                h, name = line.split()
                gold[name] = h
        for logical, h in gold.items():
            d = self.rust if logical.startswith("rust/") else self.luau
            self.assertEqual(sha(d / logical.split("/", 1)[1]), h, logical)

    def test_is_deterministic(self):
        out = Path(tempfile.mkdtemp())
        (out / "r").mkdir()
        (out / "l").mkdir()
        for f in (ROOT / "harness/src/luau").glob("extra_*.rs"):
            (out / "r" / f.name).write_bytes(f.read_bytes())
        p = run([sys.executable, TOOLS / "luaxite_gen.py", "--azalea", FAKE, "--rustdoc", FAKE_RDJ, "--rust-out", out / "r", "--luau-out", out / "l"])
        self.assertEqual(p.returncode, 0, p.stderr)
        for name in ["gen_client.rs", "gen_events.rs", "gen_types.rs"]:
            self.assertEqual(sha(out / "r" / name), sha(self.rust / name))
        self.assertEqual(sha(out / "l/azalea.d.luau"), sha(self.luau / "azalea.d.luau"))

    def test_no_absolute_paths_leak_into_outputs(self):
        for t in (self.client, self.events, self.types, self.dl, self.report):
            self.assertNotRegex(t, r"/home/|/tmp/|/Users/")


class DLuauStructure(Base):
    def test_extern_types_open_and_close(self):
        opens = len(re.findall(r"^declare extern type \w+ with$", self.dl, re.M))
        ends = len(re.findall(r"^end$", self.dl, re.M))
        self.assertEqual(opens, ends)
        self.assertGreaterEqual(opens, 3)

    def test_declares_bot_global(self):
        self.assertIn("declare bot: Bot", self.dl)

    def test_expected_classes(self):
        for cls in ["Bot", "Entity", "Container"]:
            self.assertIn(f"declare extern type {cls} with", self.dl)

    def test_no_duplicate_non_overloaded_functions(self):
        seen = {}
        for cls, name in d_luau_functions(self.dl):
            seen.setdefault((cls, name), 0)
            seen[(cls, name)] += 1
        dups = {k: n for k, n in seen.items() if n > 1 and k[1] not in {"on", "wait_for"}}
        self.assertEqual(dups, {})

    def test_every_event_has_on_and_wait_for_overloads(self):
        for ev in EVENTS:
            self.assertIn(f'function on(self, event: "{ev}"', self.dl)
            self.assertIn(f'function wait_for(self, event: "{ev}")', self.dl)

    def test_hand_fired_update_event_is_documented(self):
        self.assertIn('event: "update"', self.dl)

    def test_every_function_takes_self_in_classes(self):
        for line in self.dl.splitlines():
            m = re.match(r"\s+function (\w+)\((.*)", line)
            if m:
                self.assertTrue(m.group(2).startswith("self"), line)

    def test_no_rust_syntax_leaks_into_luau_types(self):
        for line in self.dl.splitlines():
            if line.strip().startswith(("function", "type")):
                self.assertNotRegex(line, r"&mut|&str|Vec<|Option<|::|usize|\bu32\b|\bf64\b|\bString\b", line)

    def test_type_aliases_reference_only_known_names(self):
        known = set(re.findall(r"^type (\w+) =", self.dl, re.M)) | set(re.findall(r"declare extern type (\w+)", self.dl, re.M))
        builtin = {"number", "string", "boolean", "nil", "any", "buffer"}
        for line in self.dl.splitlines():
            if line.startswith("type "):
                body = line.split("=", 1)[1]
                body = re.sub(r'"[^"]*"', "", body)
                for w in re.findall(r"\b[A-Z]\w+\b", body):
                    self.assertIn(w, known | builtin, f"{w} in: {line[:80]}")


class Rust(Base):
    def test_every_generated_bot_method_has_a_rust_fn(self):
        part = self.dl.split("declare extern type Bot with")[1].split("-- hand-written")[0]
        for cls, name in d_luau_functions("declare extern type Bot with" + part + "\nend"):
            if name in {"on", "wait_for"}:
                continue
            self.assertRegex(self.client, rf"\bfn {name}\(", name)

    def test_event_names_in_the_event_table_match_d_luau(self):
        for ev in EVENTS:
            self.assertIn(f'"{ev}"', self.events)

    def test_every_event_variant_fires_its_handler(self):
        for var in ["Init", "Login", "Chat", "Tick", "AddPlayer", "KeepAlive", "Disconnect", "ConnectionFailed", "Death"]:
            self.assertIn(f"Event::{var}", self.events)

    def test_enums_convert_both_ways(self):
        for e in ["Direction", "WalkDirection"]:
            self.assertIn(f"Lua{e}", self.types)
        self.assertGreaterEqual(self.types.count("impl FromLua for"), 2)
        self.assertGreaterEqual(self.types.count("impl IntoLua for"), 5)

    def test_braces_are_balanced(self):
        for t in (self.client, self.events, self.types):
            code = re.sub(r'"(\\.|[^"\\])*"', '""', t)
            code = re.sub(r"//.*", "", code)
            self.assertEqual(code.count("{"), code.count("}"))
            self.assertEqual(code.count("("), code.count(")"))


class Report(Base):
    def test_report_counts_match_d_luau(self):
        m = re.search(r"`Client` -> `LuaClient` / `Bot`:\*\* (\d+) methods generated", self.report)
        self.assertTrue(m)
        part = self.dl.split("declare extern type Bot with")[1].split("-- hand-written")[0]
        names = {n for _, n in d_luau_functions("declare extern type Bot with" + part + "\nend")} - {"on", "wait_for"}
        self.assertEqual(int(m.group(1)), len(names))

    def test_report_lists_events(self):
        for ev in EVENTS:
            self.assertIn(f"- `{ev}`", self.report)

    def test_report_lists_hand_written_methods(self):
        self.assertIn("Hand-written methods", self.report)
        self.assertIn("`block_at`", self.report)


class Failures(unittest.TestCase):
    def test_missing_rustdoc_dir(self):
        p = run([sys.executable, TOOLS / "luaxite_gen.py", "--azalea", FAKE, "--rustdoc", "/nonexistent", "--rust-out", "/tmp/x", "--luau-out", "/tmp/y"])
        self.assertEqual(p.returncode, 1)
        self.assertIn("no rustdoc JSON directory", p.stderr)

    def test_missing_config_file(self):
        p = run([sys.executable, TOOLS / "luaxite_gen.py", "--azalea", FAKE, "--rustdoc", FAKE_RDJ, "--rust-out", "/tmp/x", "--luau-out", "/tmp/y", "--config", "/nonexistent.toml"])
        self.assertEqual(p.returncode, 1)
        self.assertIn("cannot read", p.stderr)

    def test_bad_config_key_type(self):
        with tempfile.TemporaryDirectory() as d:
            cfg = Path(d) / "c.toml"
            cfg.write_text((ROOT / "bindgen.toml").read_text().replace("deny_methods = []", 'deny_methods = "not a list"'))
            p = run([sys.executable, TOOLS / "luaxite_gen.py", "--azalea", FAKE, "--rustdoc", FAKE_RDJ, "--rust-out", d, "--luau-out", d, "--config", cfg])
            self.assertEqual(p.returncode, 1)
            self.assertIn("deny_methods", p.stderr)

    def test_unknown_flag_is_usage_error(self):
        p = run([sys.executable, TOOLS / "luaxite_gen.py", "--nope"])
        self.assertEqual(p.returncode, 2)

    def test_deny_methods_removes_a_method(self):
        with tempfile.TemporaryDirectory() as d:
            cfg = Path(d) / "c.toml"
            cfg.write_text((ROOT / "bindgen.toml").read_text().replace("deny_methods = []", 'deny_methods = ["chat"]'))
            rust, luau = Path(d) / "r", Path(d) / "l"
            rust.mkdir()
            luau.mkdir()
            for f in (ROOT / "harness/src/luau").glob("extra_*.rs"):
                (rust / f.name).write_bytes(f.read_bytes())
            p = run([sys.executable, TOOLS / "luaxite_gen.py", "--azalea", FAKE, "--rustdoc", FAKE_RDJ, "--rust-out", rust, "--luau-out", luau, "--config", cfg])
            self.assertEqual(p.returncode, 0, p.stderr)
            dl = (luau / "azalea.d.luau").read_text()
            self.assertNotIn("function chat(self, content", dl)
            self.assertIn("function write_chat_packet", dl)


class GoldenScript(unittest.TestCase):
    def test_golden_compare_passes(self):
        p = run(["sh", "tools/golden.sh", "compare"])
        self.assertEqual(p.returncode, 0, p.stdout + p.stderr)

    def test_golden_detects_a_changed_file(self):
        with tempfile.TemporaryDirectory() as d:
            rust, luau = Path(d) / "r", Path(d) / "l"
            rust.mkdir()
            luau.mkdir()
            for f in (ROOT / "harness/src/luau").glob("gen_*.rs"):
                (rust / f.name).write_bytes(f.read_bytes())
            for f in (ROOT / "harness/luau").iterdir():
                (luau / f.name).write_bytes(f.read_bytes())
            (luau / "azalea.d.luau").write_text((luau / "azalea.d.luau").read_text() + "-- tampered\n")
            p = run(["sh", "tools/golden.sh", "compare", "fake", rust, luau])
            self.assertEqual(p.returncode, 1)


