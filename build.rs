use std::env;
use std::fmt::Write as _;
use std::fs;
use std::path::{Path, PathBuf};
use std::process::{Command, exit};

fn fail(msg: &str) -> ! {
    eprintln!("error: {msg}");
    exit(1)
}

fn find_main(src: &Path) -> PathBuf {
    for name in ["main.luau", "main.lua"] {
        let p = src.join(name);
        if p.is_file() {
            return p;
        }
    }
    fail(&format!(
        "no entry script: expected src/main.luau (or src/main.lua) in {}",
        src.display()
    ))
}

fn walk(dir: &Path, scripts: &mut Vec<PathBuf>, dirs: &mut Vec<PathBuf>) {
    dirs.push(dir.to_path_buf());
    let rd =
        fs::read_dir(dir).unwrap_or_else(|e| fail(&format!("cannot read {}: {e}", dir.display())));
    let mut entries: Vec<PathBuf> = rd.filter_map(|e| e.ok()).map(|e| e.path()).collect();
    entries.sort();
    for p in entries {
        if p.is_dir() {
            walk(&p, scripts, dirs);
        } else if p.is_file() {
            let name = p.file_name().and_then(|n| n.to_str()).unwrap_or("");
            if name.ends_with(".luau") && !name.ends_with(".d.luau") {
                scripts.push(p);
            }
        }
    }
}

fn utf8<'a>(p: &'a Path) -> &'a str {
    p.to_str()
        .unwrap_or_else(|| fail(&format!("path is not valid UTF-8: {}", p.display())))
}

fn module_name(src: &Path, file: &Path) -> String {
    let rel = file.strip_prefix(src).unwrap_or(file).with_extension("");
    let parts: Vec<String> = rel
        .components()
        .map(|c| c.as_os_str().to_string_lossy().into_owned())
        .collect();
    parts.join(".")
}

fn main() {
    let root = PathBuf::from(env::var_os("CARGO_MANIFEST_DIR").unwrap_or_else(|| ".".into()));
    let out_dir = match env::var_os("OUT_DIR") {
        Some(v) => PathBuf::from(v),
        None => fail("OUT_DIR is not set (run through cargo)"),
    };
    let src = root.join("src");

    let main_file = find_main(&src);

    let run = Command::new("python3")
        .args(["tools/bindgen.py", "--root", "."])
        .arg("--out")
        .arg(&out_dir)
        .current_dir(&root)
        .output()
        .unwrap_or_else(|e| {
            fail(&format!(
                "cannot run python3 (needed to generate the bindings): {e}"
            ))
        });
    print!("{}", String::from_utf8_lossy(&run.stdout));
    if !run.status.success() {
        let err = String::from_utf8_lossy(&run.stderr);
        let err = err.trim();
        if err.is_empty() {
            fail(&format!("tools/bindgen.py failed ({})", run.status));
        }
        eprintln!("{err}");
        exit(1);
    }

    let mut files = Vec::new();
    let mut dirs = Vec::new();
    walk(&src, &mut files, &mut dirs);
    let mut scripts: Vec<(String, PathBuf)> = files
        .into_iter()
        .map(|f| (module_name(&src, &f), f))
        .collect();
    scripts.sort();

    let mut text = String::new();
    let _ = writeln!(
        text,
        "// @generated by build.rs from src/**.luau; do not edit."
    );
    let _ = writeln!(
        text,
        "pub const MAIN: &str = include_str!({:?});",
        utf8(&main_file)
    );
    let _ = writeln!(text, "pub const SCRIPTS: &[(&str, &str)] = &[");
    for (name, path) in &scripts {
        let _ = writeln!(
            text,
            "    ({:?}, include_str!({:?})),",
            name.as_str(),
            utf8(path)
        );
    }
    let _ = writeln!(text, "];");
    let dest = out_dir.join("scripts.rs");
    fs::write(&dest, text)
        .unwrap_or_else(|e| fail(&format!("cannot write {}: {e}", dest.display())));

    println!("cargo:rerun-if-changed=build.rs");
    for d in &dirs {
        println!("cargo:rerun-if-changed={}", d.display());
    }
    for (_, f) in &scripts {
        println!("cargo:rerun-if-changed={}", f.display());
    }
    if !scripts.iter().any(|(_, f)| *f == main_file) {
        println!("cargo:rerun-if-changed={}", main_file.display());
    }
}
