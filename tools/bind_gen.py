#!/usr/bin/env python3
"""Generate the Rust that binds the fns selected by tools/bind_scan.py to a Luau state.

Output: `pub fn register(lua: &mlua::Lua) -> mlua::Result<()>`; every bound fn becomes a Luau global of the same name.
Argument types: i8..i64, u8..u64, isize, usize, f32, f64, bool, String, or Option<one of those> (nil is None).
A first parameter `&Lua` / `&mlua::Lua` is passed the state and is not a Luau argument.
Return: nothing, `()`, or one of those; or `Result<T, E>` / `anyhow::Result<T>` / `mlua::Result<T>` with T like that (Err raises a Luau error with E's text).
A fn with another type is left out (stderr `unsupported path:line fn type`); a repeated name keeps the first (stderr `dup name`).
The fn is called as `crate::<module path of its file>::name`: rust/main.rs is the crate root, rust/a/mod.rs and rust/a.rs are `a`; the glue in rust_binds/luau/ is `crate::luau` (main.rs declares it with #[path]).
The generated code lives in `crate::luau`, so a private fn is only callable from rust/main.rs and rust_binds/luau/mod.rs; a private fn of another file is
left out (stderr `invisible path:line fn`). `#[cfg(..)]` on the fn, on the `mod x;` declarations that lead to its file, are copied onto its line.
"""
import argparse
import re
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import bind_scan  # noqa: E402

PRIMS = {"i8", "i16", "i32", "i64", "u8", "u16", "u32", "u64", "isize", "usize", "f32", "f64", "bool", "String"}
HEAD = "// @generated by tools/bind_gen.py: do not edit.\n"


def module_path(label):
    """`rust_binds/luau/x.rs` -> `crate::luau::x`; `rust/main.rs` -> `crate`; `rust_binds/luau/mod.rs` -> `crate::luau`."""
    parts = Path(label).with_suffix("").parts[1:]
    if parts and parts[-1] in ("mod", "main"):
        parts = parts[:-1]
    return "::".join(("crate", *parts))


LUA_REF = {"&Lua", "&mlua::Lua"}
RESULT = re.compile(r"(?:anyhow::|mlua::|std::result::)?Result<(.*)>")
OPTION = re.compile(r"Option<(.*)>")


def arg_ok(ty):
    m = OPTION.fullmatch(ty)
    return (m.group(1) if m else ty) in PRIMS


def split_sig(params, ret):
    """(inject, args, is_result, bad): `args` are the Luau-visible params; `bad` is the first type that cannot cross to Luau, else None."""
    inject = bool(params) and params[0]["ty"] in LUA_REF
    args = params[inject:]
    for p in args:
        if not arg_ok(p["ty"]):
            return inject, args, False, p["ty"]
    m = RESULT.fullmatch(ret)
    parts = bind_scan.split_top(m.group(1)) if m else []
    ok = parts[0] if parts else ret
    return inject, args, bool(m), None if ok in PRIMS | {"", "()"} else ret


def visible(path, vis):
    """The generated register() is in `crate::luau`: it sees pub fns, and the private fns of the crate root and of `crate::luau` itself."""
    return vis or path in ("crate", "crate::luau")


def mod_cfgs(root, label):
    """`#[cfg(..)]` bodies on the `mod x;` declarations that lead from the crate root to the file `label` (rust/a/b.rs: `mod a;` in main.rs, `mod b;` in a)."""
    parts = Path(label).with_suffix("").parts[1:]
    if parts and parts[-1] in ("mod", "main"):
        parts = parts[:-1]
    out, parent = [], Path(root, "rust", "main.rs")
    for i, name in enumerate(parts):
        if parent.is_file():
            src = parent.read_text(errors="replace")
            text = bind_scan.mask(src)
            for m in re.finditer(r"\bmod\s+" + re.escape(name) + r"\s*;", text):
                out += [a for a in bind_scan.attrs_before(text, m.start(), src) if re.match(r"cfg\s*\(", a)]
        d = Path(root, Path(label).parts[0], *parts[: i + 1])
        parent = d / "mod.rs" if (d / "mod.rs").is_file() else d.with_suffix(".rs")
    return out


def statement(fn, path, args, inject=False, is_result=False, cfgs=()):
    """One `globals.set(..)` line for a fn with supported types."""
    names = [f"a{i}" for i in range(len(args))]
    if not args:
        pat = "()"
    elif len(args) == 1:
        pat = f"{names[0]}: {args[0]['ty']}"
    else:
        pat = f"({', '.join(names)}): ({', '.join(p['ty'] for p in args)})"
    call = f"{path}::{fn}({', '.join((['lua'] if inject else []) + names)})"
    result = f"{call}.map_err(|e| mlua::Error::runtime(e.to_string()))" if is_result else f"Ok({call})"
    line = f'globals.set("{fn}", lua.create_function(|{"lua" if inject else "_"}, {pat}| {result})?)?;'
    if cfgs:  # a block: attributes on a plain statement are fine, on the `?` expression inside it they are not
        return "".join(f"    #[{c}]\n" for c in cfgs) + f"    {{\n        {line}\n    }}\n"
    return f"    {line}\n"


def generate(root):
    """Rust source text for every supported fn under root/rust and root/rust_binds."""
    body, seen = [], set()
    for label, line, fn, _mode, params, ret, extra in bind_scan.scan_root(root):
        if label.startswith("rust_binds/bind/"):
            continue
        inject, args, is_result, bad = split_sig(params, ret)
        if not visible(module_path(label), extra["vis"]):
            print(f"invisible {label}:{line} {fn}", file=sys.stderr)
        elif bad is not None:
            print(f"unsupported {label}:{line} {fn} {bad}", file=sys.stderr)
        elif fn in seen:
            print(f"dup {fn} ({label}:{line})", file=sys.stderr)
        else:
            seen.add(fn)
            cfgs = mod_cfgs(root, label) + extra["cfgs"]
            body.append(statement(fn, module_path(label), args, inject, is_result, cfgs))
    head = "pub fn register(lua: &mlua::Lua) -> mlua::Result<()> {\n"
    if not body:
        return HEAD + head + "    let _ = lua;\n    Ok(())\n}\n"
    return HEAD + head + "    let globals = lua.globals();\n" + "".join(body) + "    Ok(())\n}\n"


def main():
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--root", default=".")
    ap.add_argument("--out", help="write here instead of stdout")
    args = ap.parse_args()
    text = generate(args.root)
    if args.out:
        Path(args.out).write_text(text)
    else:
        sys.stdout.write(text)


if __name__ == "__main__":
    main()
